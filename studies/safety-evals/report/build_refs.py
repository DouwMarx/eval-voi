#!/usr/bin/env python3
"""Write refs.bib with exactly the entries the paper and the extended report cite.

Sources, first match wins: extra.bib (entries added for this report, checked against
arXiv or the publisher when added), research/bib/*.bib, research/refs.bib, the archived
pilots' refs.bib. Drops provenance fields (note, abstract). Fails if a cited key is
in no source, or if an entry carries no DOI, arXiv id or URL (CoRL desk-rejects
papers that cite references which do not exist).

Usage: python3 studies/safety-evals/report/build_refs.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
TEX = sorted(HERE.glob("*.tex")) + sorted(HERE.glob("sections/*.tex")) + sorted(HERE.glob("extended/*.tex"))
SOURCES = [HERE / "extra.bib", *sorted((ROOT / "research" / "bib").glob("*.bib")),
           ROOT / "research" / "refs.bib", *sorted((ROOT / "archive" / "pilots").glob("*/report/refs.bib"))]
CITE = re.compile(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}")
KEEP_NOTE = re.compile(r"arXiv[:\s]*\d{4}\.\d{4,5}(v\d+)?", re.I)
DROP = ("note", "abstract", "file", "keywords")
IDENT = re.compile(r"\b(doi|eprint|url)\s*=|\\url\{https?://|arXiv[:\s]*\d{4}\.\d{4,5}|arxiv\.org/abs/", re.I)


def entries(text: str) -> dict[str, str]:
    """key -> full entry text, by brace matching from each '@type{key,'."""
    out = {}
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        if m.group(1).lower() in ("comment", "string", "preamble"):
            continue
        depth, i = 0, m.end() - 1
        start = text.index("{", m.start())
        for i in range(start, len(text)):
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            if depth == 0:
                break
        out.setdefault(m.group(2), text[m.start():i + 1])
    return out


def drop_fields(entry: str, names=DROP) -> str:
    """The entry without the named fields (the research bib files keep provenance in
    'note', which is for us, not for the reader; a note that is only an arXiv id stays)."""
    for name in names:
        start = 0
        while (m := re.search(rf",\s*{name}\s*=\s*", entry[start:], re.I)):
            m0, i = start + m.start(), start + m.end()
            if entry[i] == "{":
                depth = 0
                for j in range(i, len(entry)):
                    depth += {"{": 1, "}": -1}.get(entry[j], 0)
                    if depth == 0:
                        break
                end = j + 1
            else:   # a bare or quoted value up to the next comma or the closing brace
                end = i + re.search(r'^("[^"]*"|[^,}]*)', entry[i:]).end()
            if KEEP_NOTE.fullmatch(entry[i:end].strip("{} ")):
                start = end   # a note that is only an arXiv id is the entry's identifier: keep it
                continue
            entry = entry[:m0] + entry[end:]
    return entry


def cited() -> list[str]:
    keys = []
    for tex in TEX:
        body = "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in tex.read_text().splitlines())
        for group in CITE.findall(body):
            keys += [k.strip() for k in group.split(",") if k.strip()]
    return sorted(set(keys))


def main() -> int:
    pool: dict[str, str] = {}
    for src in SOURCES:
        if src.exists():
            for key, entry in entries(src.read_text()).items():
                pool.setdefault(key, entry)
    keys = cited()
    missing = [k for k in keys if k not in pool]
    unverified = [k for k in keys if k in pool and not IDENT.search(drop_fields(pool[k]))]
    if missing or unverified:
        if missing:
            print("build_refs: cited but in no source: " + ", ".join(missing), file=sys.stderr)
        if unverified:
            print("build_refs: no DOI, arXiv id or URL: " + ", ".join(unverified), file=sys.stderr)
        return 1
    out = HERE / "refs.bib"
    out.write_text("% generated by build_refs.py from extra.bib, research/ and the pilots; do not edit\n\n"
                   + "\n\n".join(drop_fields(pool[k]) for k in keys) + "\n")
    print(f"build_refs: {len(keys)} entries -> {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
